# -*- coding: utf-8 -*-
r"""Export trained 12ch GRU streaming ckpt -> dsp/fw/stream_det_w.h (int8 per-row).

Rows quantized symmetric per-output-row (same scheme as eval_stream2's
quant_int8_state_dict — deployment matches E2 sim). GRU gate order = torch (r,z,n)."""
from __future__ import annotations
import argparse, json, os, sys

import numpy as np
import torch

sys.stdout.reconfigure(encoding="utf-8")
ROOT = r"E:\NewPaper20261110"
sys.path.insert(0, os.path.join(ROOT, "models"))
from stream_nets import build, SUBSET12                      # noqa: E402


def q_rows(w: np.ndarray):
    """w (out,in) -> q int8 (out,in), s (out,)"""
    s = np.abs(w).max(axis=1, keepdims=True) / 127.0
    s = np.clip(s, 1e-12, None)
    q = np.clip(np.round(w / s), -127, 127).astype(np.int8)
    return q.flatten(), s.flatten().astype(np.float32)


def emit_arr(fh, ctype, name, arr, per_line=16):
    fh.write(f"const {ctype} {name}[{arr.size}] = {{\n")
    flat = arr.flatten()
    for i in range(0, flat.size, per_line):
        fh.write(",".join(str(v) for v in flat[i:i + per_line]) + ",\n")
    fh.write("};\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default="stream_gru_12ch_d48_s0.pt")
    args = ap.parse_args()
    model = build("gru", m=len(SUBSET12), d=48)
    sd = torch.load(os.path.join(ROOT, "ckpt", args.ckpt), weights_only=True, map_location="cpu")
    model.load_state_dict(sd)

    g = lambda k: sd[k].numpy().astype(np.float64)
    blocks = {}
    blocks["W_in_q"], blocks["W_in_s"] = q_rows(g("in_proj.weight"))
    blocks["b_in"] = sd["in_proj.bias"].numpy()
    for li in range(2):
        p = f"rnn.weight_ih_l{li}"
        blocks[f"Wih{li}_q"], blocks[f"sih{li}"] = q_rows(g(p))
        blocks[f"bih{li}"] = sd[f"rnn.bias_ih_l{li}"].numpy()
        p = f"rnn.weight_hh_l{li}"
        blocks[f"Whh{li}_q"], blocks[f"shh{li}"] = q_rows(g(p))
        blocks[f"bhh{li}"] = sd[f"rnn.bias_hh_l{li}"].numpy()
    blocks["W_hd_q"], blocks["W_hd_s"] = q_rows(g("head.weight"))
    blocks["b_hd"] = sd["head.bias"].numpy()

    hdr = os.path.join(ROOT, "dsp", "fw", "stream_det_w.h")
    with open(hdr, "w", encoding="ascii", newline="\n") as fh:
        fh.write("/* stream_det_w.h auto-generated by export_weights.py from %s\n"
                 " * int8 per-row symmetric + row scales. DO NOT EDIT. */\n" % args.ckpt)
        fh.write("#ifndef STREAM_DET_W_H\n#define STREAM_DET_W_H\n\n")
        for name, arr in blocks.items():
            t = "signed char" if name.endswith("_q") else "float"
            emit_arr(fh, t, name, arr)
        fh.write("#endif\n")
    n_int8 = sum(b.size for k, b in blocks.items() if k.endswith("_q"))
    json.dump({"ckpt": args.ckpt, "n_int8": int(n_int8),
               "words_int8_unpacked": int(n_int8),
               "n_float": int(sum(b.size for k, b in blocks.items() if not k.endswith("_q")))},
              open(os.path.join(ROOT, "dsp", "fw", "stream_det_w_meta.json"), "w"))
    print(f"[export] {hdr}: int8 {n_int8} (unpacked {n_int8} words), "
          f"float {sum(b.size for k, b in blocks.items() if not k.endswith('_q'))}")


if __name__ == "__main__":
    main()
