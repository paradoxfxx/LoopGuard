# -*- coding: utf-8 -*-
"""用当前(v4)模型重标定: 90s clean 捕获 -> mu/sigma_raw -> 重生成 stream_det_cal.h"""
import json, os, sys, time
import numpy as np
sys.stdout.reconfigure(encoding="utf-8")
HIL_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HIL_DIR, "..")
TSE = os.path.join(HIL_DIR, "ieee33", "ieee33_1ph.tse")
SIG7 = ["v701", "v706", "v712", "v718", "v725", "v733", "i_head"]

from typhoon.api import hil
from typhoon.api.schematic_editor import model as mdl
import typhoon.test.capture as cap

mdl.load(TSE)
cpd = mdl.get_compiled_model_file(TSE)
hil.load_model(str(cpd))
hil.start_simulation()          # 模型重载+GPIO3已低 -> SWiso 复归闭合
hil.wait_sec(2)
print("[hil] v733_rep =", hil.read_analog_signal("v733_rep"), "(需≈0.93)")
time.sleep(1.0)
for s in ("atk_v701","atk_v703","atk_v706","atk_v709","atk_v712","atk_v715",
          "atk_v718","atk_v725","atk_v730","atk_v733","atk_i_head"):
    hil.set_scada_input_value(s, 0.0)
hil.set_scada_input_value("sw_load724", 1.0)
r = cap.start_capture(signals=[s + "_rep" for s in SIG7], duration=90.0, rate=1000)
time.sleep(3)
df = cap.get_capture_results(r)
arr = np.asarray(df)
fs = arr.shape[0] / 90.0
DEC = 100  # 1kHz -> 10Hz (与固件池化一致)
n = (len(arr)//DEC)*DEC
pool = arr[:n].reshape(n//DEC, DEC, arr.shape[1]).mean(axis=1)
mu = pool.mean(axis=0)
sig_pool = pool.std(axis=0)
sig_raw = sig_pool * np.sqrt(DEC)     # 固件池化100 -> z噪声=1sigma
print("mu   =", [round(float(x), 6) for x in mu])
print("sraw =", [round(float(x), 6) for x in sig_raw])
json.dump({"mu": mu.tolist(), "sigma_raw": sig_raw.tolist(), "fs": fs,
           "date": time.strftime("%Y-%m-%d %H:%M"), "model": "v4"},
          open(os.path.join(ROOT, "results", "cal_v4.json"), "w"))
h = "/* stream_det_cal.h - recalibrated on v4 model %s (mu = 90s clean mean, z = 10/sigma_raw)\n * generated by hil/recal_cal.py, do not edit */\n" % time.strftime("%Y-%m-%d")
h += "static const float CAL_MU[7] = {%s};\n" % ", ".join("%.6ff" % v for v in mu)
h += "static const float CAL_Z[7] = {%s};\n" % ", ".join("%.3ff" % (10.0 / s) for s in sig_raw)
open(os.path.join(ROOT, "dsp", "fw", "stream_det_cal.h"), "w", encoding="ascii", newline="\n").write(h)
print(h)
hil.stop_simulation()
